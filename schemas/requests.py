"""
API Request Schemas
===================
Pydantic schemas for incoming client requests (text query, retrieve, evaluate).
"""

from typing import Optional, List
from pydantic import BaseModel, Field


class TextQueryRequest(BaseModel):
    query: str = Field(
        ...,
        description="The user query in Gujarati, Hindi, or English.",
        example="વાઇનની બોટલમાં કેટલા ઔંસ હોય છે"
    )
    language: Optional[str] = Field(
        default="gu",
        description="Language code for routing ('gu', 'hi', or 'auto')."
    )
    top_k: int = Field(
        default=5,
        ge=1,
        le=20,
        description="Number of top context chunks to retrieve."
    )
    use_reranker: bool = Field(
        default=False,
        description="Whether to apply the secondary listwise re-ranker stage."
    )
    sort_by: str = Field(
        default="rrf",
        description="Sorting strategy for retrieved documents ('rrf', 'dense', 'sparse', 'rerank')."
    )
    auto_detect_language: bool = Field(
        default=True,
        description="Whether to automatically detect language script if language is auto or ambiguous."
    )
    evaluate: bool = Field(
        default=False,
        description="Whether to perform DeepEval evaluation after generating the answer."
    )
    voice_reply: bool = Field(
        default=False,
        description="Whether to synthesize and return voice speech audio using Sarvam Bulbul v3."
    )
    query_id: Optional[int] = Field(
        default=None,
        description="Optional Golden query ID to force ground-truth matching."
    )


class TTSRequest(BaseModel):
    text: str = Field(..., description="Text to synthesize to speech audio.")
    language: Optional[str] = Field(default="gu", description="Language code ('gu', 'hi', 'gu-IN', 'hi-IN').")
    speaker: Optional[str] = Field(default="shubh", description="Voice speaker identity.")
    pace: Optional[float] = Field(default=1.0, ge=0.5, le=2.0, description="Speech pace/speed.")



class RetrieveRequest(BaseModel):
    query: str = Field(
        ...,
        description="Search query to retrieve passages for.",
        example="મેનહટન પ્રોજેક્ટ શું હતો?"
    )
    language: Optional[str] = Field(
        default="gu",
        description="Language code for routing ('gu', 'hi', or 'auto')."
    )
    top_k: int = Field(
        default=5,
        ge=1,
        le=50,
        description="Number of top retrieved passages."
    )
    use_reranker: bool = Field(
        default=False,
        description="Whether to apply secondary listwise re-ranking."
    )
    sort_by: str = Field(
        default="rrf",
        description="Sorting strategy: 'rrf', 'dense', 'sparse', 'rerank'."
    )
    auto_detect_language: bool = Field(
        default=True,
        description="Whether to automatically detect language script."
    )


class EvaluateRequest(BaseModel):
    question: str = Field(..., description="The original question.")
    generated_answer: str = Field(..., description="The answer generated by the system.")
    language: Optional[str] = Field(default="gu", description="Language code ('gu', 'hi').")
    retrieved_contexts: List[str] = Field(default=[], description="List of context strings passed to the generator.")
    query_id: Optional[int] = Field(default=None, description="Optional Golden query ID.")
