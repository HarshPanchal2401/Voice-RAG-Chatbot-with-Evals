# snapshot
# ---------------------------------------------------------------------------------------------

def build_snapshot(args: argparse.Namespace) -> Path:
    from evaluation.client import RAGClient, make_inprocess_router

    loader = GoldenDataLoader(seed=args.seed)
    records = loader.load_records(language=args.lang, sample_size=args.sample, limit=args.limit,
                                  dataset_path=args.dataset)
    if args.mode == "inprocess":
        client = RAGClient(mode="inprocess", router=make_inprocess_router())
    else:
        client = RAGClient(mode="server", base_url=args.base_url)
    health = client.check()
    out_records = []
    errors = 0
    for i, r in enumerate(records, 1):
        snap = {k: r.get(k) for k in ("query_id", "language", "query_type", "question", "ground_truth_answer",
                                       "ground_truth_contexts", "ground_truth_passage_ids", "ground_truth_doc_keys",
                                       "reference_reviewed")}
        snap["ground_truth_doc_keys"] = snap.get("ground_truth_doc_keys") or gold_doc_keys(r)
        snap.update({"k": args.k, "use_reranker": args.rerank, "retrieved_doc_keys": [], "retrieved_contexts": [],
                     "retrieved_passage_ids": [], "retrieval_timings": {}, "retrieval_error": None})
        try:
            if args.with_answers:
                res = client.generate(r["question"], language=r["language"], top_k=args.k, use_reranker=args.rerank)
                docs = res.get("documents") or []
                snap.update({
                    "generated_answer": res.get("answer"),
                    "generator_model": res.get("model"),
                    "no_answer": res.get("no_answer"),
                    "answer_language": res.get("answer_language"),
                    "generation_timings": {"llm_ms": res.get("llm_ms"), "ttft_ms": res.get("ttft_ms"),
                                           "total_ms": res.get("total_ms"), "client_ms": res.get("client_ms")},
                    "generation_error": None,
                })
                timings = res.get("retrieval_timings") or {}
            else:
                res = client.retrieve(r["question"], language=r["language"], top_k=args.k, use_reranker=args.rerank)
                docs = res.get("documents") or []
                timings = dict(res.get("timings") or {})
                timings["client_ms"] = res.get("client_ms")
            snap["retrieved_doc_keys"] = doc_keys_from_documents(docs)
            snap["retrieved_contexts"] = [d.get("text", "") for d in docs]
            snap["retrieved_passage_ids"] = [d.get("passage_id") for d in docs]
            snap["retrieval_timings"] = timings
        except Exception as e:  # noqa: BLE001 - recorded, never replaced by ground truth
            errors += 1
            msg = f"{type(e).__name__}: {e}"
            snap["retrieval_error"] = msg
            snap["retrieved_doc_keys"] = []
            snap["retrieved_contexts"] = []
            if args.with_answers:
                snap.update({"generated_answer": None, "generator_model": None, "generation_error": msg})
        out_records.append(snap)
        print(f"[{i}/{len(records)}] {r.get('language')} {r.get('query_id')} "
              f"{'ERROR ' + snap['retrieval_error'] if snap['retrieval_error'] else 'ok'}")
    n_q = len({r.get("query_id") for r in records})
    ts = time.strftime("%Y%m%d_%H%M%S")
    folder = COMBINED_DIR if args.lang == "combined" else DATA_DIR / LANG_FOLDERS[args.lang]
    out = save_jsonl(out_records, folder / f"snapshot_{args.lang}_{n_q}q_{'rag' if args.with_answers else 'retrieval'}_{ts}.jsonl")
    man = dataset_manifest(out, loader.sources, generator="evaluation.combine_datasets snapshot", seed=args.seed,
                           counts={**_counts(out_records), "errors": errors},
                           params={"k": args.k, "use_reranker": args.rerank, "with_answers": args.with_answers,
                                   "mode": args.mode, "client": client.describe(), "server_health": health},
                           code_files=CODE_FILES)
    man["llm_calls"] = "generation by the RAG pipeline" if args.with_answers else 0
    write_json(manifest_path_for(out), man)
    print(f"Snapshot: {out} ({len(out_records)} records, {errors} errors)")
    if errors:
        print("WARNING: some records failed; they are kept with empty retrieval + error flags and will be counted "
              "as error records (not scored) by the evaluation.")
    return out


