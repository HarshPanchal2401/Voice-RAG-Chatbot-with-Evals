# retire-legacy
# ---------------------------------------------------------------------------------------------

def retire_legacy(combined_dir: Path = COMBINED_DIR, data_dir: Path = DATA_DIR) -> Optional[Path]:
    present = [combined_dir / f for f in LEGACY_FILES if (combined_dir / f).exists()]
    if not present:
        print("No legacy combined files present.")
        return None
    src: Dict[tuple, Dict[str, Any]] = {}
    for lg in ("gu", "hi"):
        p = data_dir / LANG_FOLDERS[lg] / "golden_dataset_full.jsonl"
        if p.exists():
            for r in read_jsonl(p, lg):
                src[(lg, r.get("query_id"))] = r
    facts = {}
    for p in present:
        if p.suffix != ".jsonl":
            facts[p.name] = {"sha256": sha256_file(p)}
            continue
        recs = [json.loads(line) for line in open(p, encoding="utf-8") if line.strip()]
        diff = 0
        for r in recs:
            s = src.get((r.get("language"), r.get("query_id")))
            ref = r.get("ground_truth_answer") or r.get("expected_output")
            if s is not None and ref != s.get("ground_truth_answer"):
                diff += 1
        models = Counter((r.get("generation_timings") or {}).get("model") for r in recs if r.get("generated_answer"))
        facts[p.name] = {
            "sha256": sha256_file(p),
            "records": len(recs),
            "distinct_query_ids": len({r.get("query_id") for r in recs}),
            "reference_answers_differing_from_source": diff,
            "has_retrieved_doc_keys": any("retrieved_doc_keys" in r for r in recs),
            "saved_answer_generator_models": {str(k): v for k, v in models.items()},
        }
    dest = combined_dir / "legacy_2026-09"
    dest.mkdir(parents=True, exist_ok=True)
    for p in present:
        shutil.move(str(p), str(dest / p.name))
    note = {
        "status": "RETIRED - do not use for evaluation",
        "retired_by": "python -m evaluation.combine_datasets retire-legacy",
        "retired_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "reasons": [
            "retrieved passages are identified by bare passage_id, which is not unique across the corpus "
            "(relevance must use doc_key = query_id:passage_id); --use-cached refuses them",
            "some reference answers differ from Data/<lang>/golden_dataset_full.jsonl and no code produced the change",
            "the 15 records cover only 8 distinct questions",
            "saved answers were generated by the judge model (self-judging) or carry no generator model",
            "the files on disk do not match what the old combine_datasets.py would write",
        ],
        "files": facts,
        "replacement": "python -m evaluation.combine_datasets eval-sets --n 300  (+ snapshot for cached runs)",
    }
    write_json(dest / "LEGACY_NOTE.json", note)
    print(f"Moved {len(present)} legacy files to {dest} (see LEGACY_NOTE.json)")
    return dest


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("eval-sets", help="build stratified paired eval sets (no LLM)")
    e.add_argument("--n", type=int, default=300)
    e.add_argument("--seed", type=int, default=42)
    e.add_argument("--min-per-stratum", type=int, default=0)
    e.add_argument("--keep-context-dependent", action="store_true")
    s = sub.add_parser("snapshot", help="live retrieval / RAG snapshot for --use-cached")
    s.add_argument("--lang", default="combined")
    s.add_argument("--sample", default="300")
    s.add_argument("--dataset", default=None)
    s.add_argument("--limit", type=int, default=None)
    s.add_argument("--k", type=int, default=5)
    s.add_argument("--rerank", action="store_true")
    s.add_argument("--with-answers", action="store_true", help="also run generation (production pipeline)")
    s.add_argument("--mode", choices=["server", "inprocess"], default="server")
    s.add_argument("--base-url", default="http://localhost:8000")
    s.add_argument("--seed", type=int, default=42)
    sub.add_parser("retire-legacy", help="move the old 15-record combined files out of the way")
    args = ap.parse_args(argv)
    if args.cmd == "eval-sets":
        outs = build_eval_sets(args.n, args.seed, not args.keep_context_dependent, args.min_per_stratum)
        print(json.dumps(outs, ensure_ascii=False, indent=2))
    elif args.cmd == "snapshot":
        build_snapshot(args)
    elif args.cmd == "retire-legacy":
        retire_legacy()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
