"""
Dataset builder for the Voice RAG evaluation (every transformation is code-driven)
=================================================================================
Sub-commands (all write a ``<name>.manifest.json`` next to each output with the source
files + sha256, seed, parameters, counts and code version):

  eval-sets       Stratified, language-paired eval sets from Data/<lang>/golden_dataset_full.jsonl
                  (no LLM calls). Default: 300 distinct questions per language.
                      python -m evaluation.combine_datasets eval-sets --n 300 --seed 42
                  -> Data/gujarati/eval_set_300.jsonl, Data/hindi/eval_set_300.jsonl,
                     Data/combined/eval_set_300_paired.jsonl (same 300 query_ids, GU + HI)
                  Filters (documented, on by default): ambiguous duplicate questions,
                  missing reference/gold passages, context-dependent pronoun-only questions
                  (``--keep-context-dependent`` disables the last one).

  snapshot        Live retrieval (and optionally generation) snapshot for ``--use-cached``.
                  Stores doc keys, timings and the generator model. Failures are recorded as
                  empty lists + ``retrieval_error`` / ``generation_error`` - ground truth is
                  NEVER substituted for retrieved passages.
                      python -m evaluation.combine_datasets snapshot --lang combined --sample 300 --mode server [--with-answers]

  retire-legacy   Moves the hand-edited 15-record files (bare passage ids, modified reference
                  answers, answers generated by the judge model) to Data/combined/legacy_2026-09/
                  with a machine-written note explaining why they must not be used.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from collections import Counter
from pathlib import Path
from typing import Any, Dict, List, Optional

_ROOT = Path(__file__).resolve().parent.parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass

from evaluation.data_loader import LANG_FOLDERS, GoldenDataLoader, read_jsonl  # noqa: E402
from evaluation.manifest import dataset_manifest, manifest_path_for, sha256_file, write_json  # noqa: E402
from evaluation.metrics.retrieval_metrics import doc_keys_from_documents, gold_doc_keys  # noqa: E402
from evaluation.sampling import sample_eval_records  # noqa: E402

DATA_DIR = _ROOT / "Data"
COMBINED_DIR = DATA_DIR / "combined"
EVAL_DIR = Path(__file__).resolve().parent
CODE_FILES = [EVAL_DIR / "combine_datasets.py", EVAL_DIR / "sampling.py", EVAL_DIR / "data_loader.py",
              EVAL_DIR / "metrics" / "text_utils.py", EVAL_DIR / "metrics" / "retrieval_metrics.py"]
LEGACY_FILES = ["retrieval_golden_dataset.jsonl", "generator_golden_dataset.jsonl", "pipeline_golden_dataset.jsonl",
                "dataset_summary.json"]


def save_jsonl(records: List[Dict[str, Any]], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    return path


def _counts(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    return {
        "records": len(records),
        "distinct_query_ids": len({r.get("query_id") for r in records}),
        "by_language": dict(sorted(Counter(r.get("language") for r in records).items())),
        "by_query_type": dict(sorted(Counter(r.get("query_type") for r in records).items())),
    }


# ---------------------------------------------------------------------------------------------
# eval-sets
# ---------------------------------------------------------------------------------------------

def build_eval_sets(n: int = 300, seed: int = 42, drop_context_dependent: bool = True, min_per_stratum: int = 0,
                    data_dir: Path = DATA_DIR, created: Optional[str] = None) -> Dict[str, Any]:
    sources = {lg: data_dir / LANG_FOLDERS[lg] / "golden_dataset_full.jsonl" for lg in ("gu", "hi")}
    for p in sources.values():
        if not p.exists():
            raise FileNotFoundError(f"missing source {p} (run Data/generate_golden_dataset.py first)")
    by_lang = {lg: read_jsonl(p, lg) for lg, p in sources.items()}
    res = sample_eval_records(by_lang, n, seed=seed, drop_context_dependent=drop_context_dependent,
                              min_per_stratum=min_per_stratum)
    name = f"eval_set_{n}"
    created = created or time.strftime("%Y-%m-%dT%H:%M:%S%z")
    params = {"n_questions": n, "strata_key": "query_type", "group_key": "query_id", "allocation": "largest remainder "
              "proportional" + (f", min {min_per_stratum} per stratum" if min_per_stratum else ""),
              "drop_context_dependent": drop_context_dependent, "drop_ambiguous_duplicates": True,
              "paired_languages": ["gu", "hi"]}
    outputs: Dict[str, Any] = {}
    per_lang_records: Dict[str, List[Dict[str, Any]]] = {}
    for lg in ("gu", "hi"):
        recs = []
        for r in res["records"][lg]:
            r = dict(r)
            r["language"] = lg
            r["ground_truth_doc_keys"] = gold_doc_keys(r)
            r["eval_set"] = name
            r.setdefault("reference_reviewed", False)
            recs.append(r)
        per_lang_records[lg] = recs
        out = save_jsonl(recs, data_dir / LANG_FOLDERS[lg] / f"{name}.jsonl")
        man = dataset_manifest(out, [sources[lg]], generator="evaluation.combine_datasets eval-sets", seed=seed,
                               counts={**_counts(recs), "allocation": res["allocation"], "eligible_query_ids": res["eligible"],
                                       "exclusions": res["exclusions"]},
                               params=params, created=created, code_files=CODE_FILES)
        write_json(manifest_path_for(out), man)
        outputs[lg] = {"path": str(out), "sha256": man["dataset"]["sha256"], **_counts(recs)}
    by_qid = {lg: {r["query_id"]: r for r in per_lang_records[lg]} for lg in ("gu", "hi")}
    paired = [by_qid[lg][qid] for qid in res["query_ids"] for lg in ("gu", "hi")]
    out = save_jsonl(paired, data_dir / "combined" / f"{name}_paired.jsonl")
    man = dataset_manifest(out, list(sources.values()), generator="evaluation.combine_datasets eval-sets", seed=seed,
                           counts={**_counts(paired), "allocation": res["allocation"], "eligible_query_ids": res["eligible"],
                                   "exclusions": res["exclusions"]},
                           params=params, created=created, code_files=CODE_FILES)
    write_json(manifest_path_for(out), man)
    outputs["combined"] = {"path": str(out), "sha256": man["dataset"]["sha256"], **_counts(paired)}
    return outputs


