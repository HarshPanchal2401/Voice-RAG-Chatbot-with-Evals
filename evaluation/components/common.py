"""
Shared machinery for the component evaluators
=============================================
Every evaluator runs in two phases:

1. **Pipeline phase (sequential)** - live retrieval / generation through ``RAGClient``
   (one request at a time so latency numbers are not distorted by concurrency), or the
   saved snapshot when ``--use-cached``. Failures become *error records*
   (``status="error"``): they are never judged, never scored as 0, and are counted in
   the report (the run fails above ``max_error_rate``).
2. **Scoring phase (concurrent)** - judge metrics run with ``asyncio`` + a semaphore;
   the judge itself applies token-bucket rate limiting, retries and caching.
"""

from __future__ import annotations

import asyncio
from typing import Any, Awaitable, Callable, Dict, List, Optional, Sequence

from evaluation.metrics.judge import GroqJudge, ModelRoles, check_model_roles
from evaluation.metrics.retrieval_metrics import (
    MissingDocKeyError,
    doc_keys_from_documents,
    gold_doc_keys,
    snapshot_doc_keys,
)
from evaluation.metrics.stats import latency_summary

LATENCY_FIELDS = ("retrieval_total_ms", "ttft_ms", "llm_ms", "total_ms", "client_ms", "rerank_ms")


class CachedAnswerError(ValueError):
    """Saved answers cannot be scored (unknown generator or generated by the judge)."""


def make_judge(config: Any) -> GroqJudge:
    check_model_roles(config.roles)
    return GroqJudge(model_name=config.judge_model_name, api_key=config.groq_api_key, use_cache=config.judge_cache)


def base_record(record: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "query_id": record.get("query_id"),
        "language": record.get("language"),
        "query_type": record.get("query_type", "UNKNOWN"),
        "question": record.get("question", ""),
    }


def error_record(record: Dict[str, Any], error: BaseException | str, stage: str) -> Dict[str, Any]:
    out = base_record(record)
    out.update({"status": "error", "stage": stage, "error": f"{type(error).__name__}: {error}"
                if isinstance(error, BaseException) else str(error), "scores": {}, "failed_metrics": []})
    return out


def reference_answer(record: Dict[str, Any]) -> str:
    return record.get("ground_truth_answer") or record.get("expected_output") or ""


def saved_generator_check(record: Dict[str, Any], roles: ModelRoles, allow_unknown: bool) -> Optional[str]:
    """Refuse saved answers generated by the judge model or by an unknown model."""
    gen = record.get("generator_model") or (record.get("generation_timings") or {}).get("model")
    if not gen:
        if allow_unknown:
            return "saved answer has an unknown generator model (allowed by --allow-unknown-generator)"
        raise CachedAnswerError(
            "Saved answers carry no 'generator_model'; cannot rule out self-judging. Regenerate the snapshot "
            "(python -m evaluation.combine_datasets snapshot --with-answers ...) or pass --allow-unknown-generator."
        )
    if gen.strip().lower() == roles.judge.strip().lower():
        raise CachedAnswerError(
            f"Saved answers were generated by '{gen}', which is also the judge model. Self-judged scores are "
            "not trustworthy: regenerate the answers with the production generator or choose another judge."
        )
    return None


def timings_from(res: Dict[str, Any]) -> Dict[str, Optional[float]]:
    rt = res.get("retrieval_timings") or res.get("timings") or {}
    out = {
        "retrieval_total_ms": rt.get("retrieval_total_ms"),
        "rerank_ms": rt.get("rerank_ms"),
        "ttft_ms": res.get("ttft_ms"),
        "llm_ms": res.get("llm_ms"),
        "total_ms": res.get("total_ms"),
        "client_ms": res.get("client_ms"),
    }
    return out


def live_generation(client: Any, record: Dict[str, Any], k: int, use_reranker: bool,
                    sort_by: str = "rrf") -> Dict[str, Any]:
    """Runs the production pipeline once. Raises on failure (caller makes an error record)."""
    res = client.generate(record["question"], language=record["language"], top_k=k,
                          use_reranker=use_reranker, sort_by=sort_by)
    docs = res.get("documents") or []
    answer = res.get("answer")
    if answer is None:
        raise RuntimeError("pipeline returned no answer")
    return {
        "answer": answer,
        "contexts": [d.get("text", "") for d in docs],
        "doc_keys": doc_keys_from_documents(docs),
        "timings": timings_from(res),
        "generator_model": res.get("model"),
        "no_answer": res.get("no_answer"),
        "answer_language": res.get("answer_language"),
        "trace_id": res.get("trace_id"),
    }


def cached_generation(record: Dict[str, Any], roles: ModelRoles, allow_unknown: bool) -> Dict[str, Any]:
    if record.get("generation_error") or record.get("retrieval_error"):
        raise RuntimeError(record.get("generation_error") or record.get("retrieval_error"))
    warning = saved_generator_check(record, roles, allow_unknown)
    answer = record.get("generated_answer")
    if answer is None:
        raise CachedAnswerError("snapshot record has no generated_answer")
    return {
        "answer": answer,
        "contexts": list(record.get("retrieved_contexts") or []),
        "doc_keys": snapshot_doc_keys(record),
        "timings": timings_from({**(record.get("generation_timings") or {}),
                                 "retrieval_timings": record.get("retrieval_timings") or {}}),
        "generator_model": record.get("generator_model"),
        "no_answer": record.get("no_answer"),
        "warning": warning,
    }


def gold_hit(doc_keys: Sequence[str], gold: Sequence[str]) -> Optional[bool]:
    if not gold:
        return None
    return bool(set(doc_keys) & set(gold))


async def run_concurrently(items: Sequence[Any], fn: Callable[[Any], Awaitable[Any]], concurrency: int = 4,
                           desc: str = "Scoring", show_progress: bool = True) -> List[Any]:
    sem = asyncio.Semaphore(max(1, concurrency))
    bar = None
    if show_progress:
        try:
            from tqdm import tqdm

            bar = tqdm(total=len(items), desc=desc)
        except Exception:
            bar = None

    async def _one(item):
        async with sem:
            try:
                return await fn(item)
            finally:
                if bar is not None:
                    bar.update(1)

    try:
        return await asyncio.gather(*(_one(it) for it in items))
    finally:
        if bar is not None:
            bar.close()


def progress(iterable: Sequence[Any], desc: str, show: bool = True):
    if not show:
        return iterable
    try:
        from tqdm import tqdm

        return tqdm(iterable, desc=desc)
    except Exception:
        return iterable


def latency_block(results: Sequence[Dict[str, Any]], warmup: int) -> Dict[str, Any]:
    ok = [r for r in results if r.get("status") == "ok" and r.get("timings")]
    out = {}
    for f in LATENCY_FIELDS:
        series = [r["timings"].get(f) for r in ok]
        if any(v is not None for v in series):
            out[f] = latency_summary(series, warmup=warmup)
    return out


def collect_generations(client: Any, config: Any, records: List[Dict[str, Any]], k: int,
                        use_reranker: bool, show_progress: bool = True) -> List[Dict[str, Any]]:
    """Phase 1 shared by the pipeline and application evaluators (one pipeline call per record)."""
    out = []
    for record in progress(records, f"Running pipeline (k={k}, rerank={use_reranker})", show_progress):
        item = {"record": record, "gen": None, "error": None, "stage": "pipeline"}
        try:
            if config.use_cached:
                item["gen"] = cached_generation(record, config.roles, config.allow_unknown_generator)
            else:
                item["gen"] = live_generation(client, record, k, use_reranker)
            gm = item["gen"].get("generator_model")
            if gm and gm.strip().lower() == config.judge_model_name.strip().lower():
                raise RuntimeError(f"answer was generated by the judge model '{gm}' (self-judging)")
        except Exception as e:  # noqa: BLE001
            if type(e).__name__ in ("CachedAnswerError", "StaleSnapshotError", "ModelRoleError"):
                raise
            item["error"] = e
        out.append(item)
    return out


